/** Dataset JSON-LD so the counts are machine-readable, as on the other assets. */
export function buildBuyerFeedbackDatasetSchema(canonicalUrl: string) {
  return {
    "@context": "https://schema.org",
    "@type": "Dataset",
    name: "Balance bike buyer-sentiment summaries (aggregated)",
    description: buyerFeedbackSeo.en.description,
    url: canonicalUrl,
    license: "https://balancebiketoddler.com/transparency/terms/",
    creator: { "@type": "Organization", name: "BalanceBikeToddler" },
    variableMeasured: [
      ...d.themes.map((entry) => ({
        "@type": "PropertyValue",
        name: entry.label,
        value: entry.count,
        unitText: `summaries of ${total}`,
        description: entry.note,
      })),
      ...d.hedges.map((entry) => ({
        "@type": "PropertyValue",
        name: `Hedge: ${entry.label}`,
        value: entry.count,
        unitText: `summaries of ${total}`,
      })),
    ],
  };
}

