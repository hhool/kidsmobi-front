/**
 * Mirrors the front's retired-GUIDE routes into the Worker, so the Worker's
 * D1-built sitemap never advertises a URL the site 301s.
 *
 * Why this exists: the front prerender already drops retired CMS guides from
 * generation and from dist/sitemap.xml, but the Worker builds the sitemap
 * Google actually crawls from D1 rows directly — a separate path that has to
 * be told about the retirement. Without this, the live sitemap keeps listing
 * the retired URL (and its /zh edition) while the front's does not, which is
 * exactly the drift the prune-map sync was written to end.
 *
 * Read from the front's own registry (RETIRED_STABILITY_GUIDE_PATHS) rather
 * than a copy, so the two cannot diverge. Run after any retirement change:
 *   cd front && node scripts/sync_retired_guides_to_worker.mjs
 * then redeploy the Worker.
 *
 * Mirrors front/scripts/sync_prune_map_to_worker.mjs.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = process.cwd();
const srcFile = resolve(root, "src/data/balanceBikeStability.ts");
const outFile = resolve(root, "..", "backend/api/worker/src/retiredGuides.generated.ts");

const src = readFileSync(srcFile, "utf8");

/**
 * Parse the first element of each pair in RETIRED_STABILITY_GUIDE_PATHS.
 * The target is usually a bare identifier (STABILITY_PATH) rather than a
 * quoted string, so matching on a quoted second element would silently return
 * an empty set and let the dead URL back into the sitemap.
 */
const block = /RETIRED_STABILITY_GUIDE_PATHS[^=]*=\s*\[([\s\S]*?)\n\];/.exec(src);
if (!block) {
  console.error("could not find RETIRED_STABILITY_GUIDE_PATHS in " + srcFile);
  process.exit(1);
}

const retired = [];
for (const m of block[1].matchAll(/\[\s*["']([^"']+)["']\s*,\s*([^\]]+)\]/g)) {
  retired.push({ from: m[1].replace(/\/+$/, ""), toRaw: m[2].trim() });
}
if (!retired.length) {
  console.error("RETIRED_STABILITY_GUIDE_PATHS is empty — refusing to wipe the Worker's list");
  process.exit(1);
}

// Resolve a bare-identifier target (e.g. STABILITY_PATH) from the same module,
// so the generated file records where each retired URL now points.
const targetByConst = {};
for (const m of src.matchAll(/export const ([A-Z0-9_]+)\s*=\s*["']([^"']+)["']/g)) {
  targetByConst[m[1]] = m[2];
}

const body = retired
  .map((r) => {
    const to = r.toRaw.startsWith('"') || r.toRaw.startsWith("'")
      ? r.toRaw.slice(1, -1)
      : targetByConst[r.toRaw];
    if (!to) {
      console.error(`could not resolve redirect target ${r.toRaw} for ${r.from}`);
      process.exit(1);
    }
    return `  "${r.from}": "${to}",`;
  })
  .join("\n");

const text = `// AUTO-GENERATED by front/scripts/sync_retired_guides_to_worker.mjs — do not edit by hand.
// Source of truth: the front's retirement registry
// (src/data/balanceBikeStability.ts → RETIRED_STABILITY_GUIDE_PATHS).
//
// The Worker's D1 sitemap build imports this map so it never advertises a URL
// the site 301s away. The front's prerender and dist/sitemap.xml already omit
// these; the Worker reads D1 rows directly and needs its own copy of the rule.
// Re-sync after any retirement change:
//   cd front && node scripts/sync_retired_guides_to_worker.mjs
//
// Keyed without the trailing slash, matching resolveLegacyRedirect's lookup.
export const RETIRED_GUIDE_ROUTES: Record<string, string> = {
${body}
};

/** Every retired guide route, for sitemap exclusion lookups. */
export const RETIRED_GUIDE_ROUTE_SET: ReadonlySet<string> = new Set(
  Object.keys(RETIRED_GUIDE_ROUTES),
);
`;

writeFileSync(outFile, text, "utf8");
console.log(
  `wrote ${outFile} (${retired.length} retired guide route(s)): ` +
    retired.map((r) => r.from).join(", "),
);