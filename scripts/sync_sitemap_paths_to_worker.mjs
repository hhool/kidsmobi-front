/**
 * Generates the Worker's two hardcoded sitemap page lists from the front build.
 *
 * Why this exists: the Worker builds the sitemap Google actually crawls (the
 * no-buster request on the apex), and it used to carry its own hand-written
 * copies of "which pages exist but have no CMS record". Those copies drifted —
 * when the recall record moved to /guides/risk/balance-bike-recall-record the
 * prerendered dist sitemap was correct while the Worker kept advertising the
 * retired URL and omitting its replacement. Nothing caught it: every guard
 * reads dist, and the only check that touches the live sitemap counts URLs, so
 * a 270-for-270 swap looked clean.
 *
 * So the lists are derived instead of maintained. Both are read straight out of
 * dist/sitemap.xml, which is already the single source:
 *
 *   SITEMAP_ASSET_PATHS  <- every <loc> emitted with <priority>0.9
 *   STATIC_NO_CMS_PATHS  <- every <loc> emitted without <lastmod>
 *
 * The second is the honest definition of the original comment ("pages the front
 * prerenders but that have no CMS record, so the D1 scan never sees them"): a
 * page with no record has no edit date to expose, so the prerender omits
 * <lastmod>, and that omission is already the signal.
 *
 * Run after any build that changes routes:
 *   cd front && npm run build && node scripts/sync_sitemap_paths_to_worker.mjs
 * then `npm run check:workerparity` and redeploy the Worker.
 */
import { readFileSync, writeFileSync } from 'fs';
import { resolve } from 'path';

const root = process.cwd();
const sitemapPath = resolve(root, 'dist', 'sitemap.xml');
const outFile = resolve(root, '..', 'backend', 'api', 'worker', 'src', 'workerSitemapPaths.generated.ts');

const sitemap = readFileSync(sitemapPath, 'utf8');
const entries = [...sitemap.matchAll(/<url>([\s\S]*?)<\/url>/g)].map((m) => m[1]);
if (entries.length === 0) {
  console.error(`${sitemapPath} has no <url> entries — refusing to wipe the Worker's sitemap lists`);
  process.exit(1);
}

const locOf = (entry) => (entry.match(/<loc>([^<]+)<\/loc>/) || [])[1];
const pathOf = (loc) => {
  const u = new URL(loc);
  return u.pathname;
};

// Priority 0.9: the tier the prerender reserves for the pages this domain
// stands behind. Read from the emitted XML rather than re-deriving the
// prerender's rules, so a change to sitemapPriority() shows up here for free.
const assetPaths = entries
  .filter((e) => e.includes('<priority>0.9</priority>'))
  .map((e) => pathOf(locOf(e)));

// No <lastmod> == no CMS record == invisible to the Worker's D1 scan.
const staticNoCmsPaths = entries
  .filter((e) => !e.includes('<lastmod>'))
  .map((e) => pathOf(locOf(e)));

for (const [name, list] of [['SITEMAP_ASSET_PATHS', assetPaths], ['STATIC_NO_CMS_PATHS', staticNoCmsPaths]]) {
  if (list.length === 0) {
    console.error(`${name} came out empty — the sitemap shape changed; refusing to write`);
    process.exit(1);
  }
  const dupes = list.filter((p, i) => list.indexOf(p) !== i);
  if (dupes.length > 0) {
    console.error(`${name} has duplicates: ${[...new Set(dupes)].join(', ')}`);
    process.exit(1);
  }
}

const header = `// AUTO-GENERATED by front/scripts/sync_sitemap_paths_to_worker.mjs — do not edit by hand.
// Source of truth: the front build's dist/sitemap.xml. The Worker serves the
// sitemap Google crawls, and these lists used to be hand-maintained copies that
// drifted out of sync with the prerender. Re-sync after any build that changes
// routes:  cd front && npm run build && node scripts/sync_sitemap_paths_to_worker.mjs
`;

writeFileSync(
  outFile,
  `${header}
/** Every sitemap URL the prerender emits at <priority>0.9. */
export const SITEMAP_ASSET_PATHS: ReadonlyArray<string> = [
${assetPaths.map((p) => `  ${JSON.stringify(p)},`).join('\n')}
];

/**
 * Sitemap URLs with no <lastmod>: pages the front prerenders that have no CMS
 * record, so the D1 scan never sees them and there is no honest edit date to
 * expose.
 */
export const STATIC_NO_CMS_PATHS: ReadonlyArray<string> = [
${staticNoCmsPaths.map((p) => `  ${JSON.stringify(p)},`).join('\n')}
];
`,
  'utf8',
);

console.log(
  `wrote ${outFile} (${assetPaths.length} asset at 0.9, ${staticNoCmsPaths.length} without lastmod, from ${entries.length} sitemap URL(s))`,
);
