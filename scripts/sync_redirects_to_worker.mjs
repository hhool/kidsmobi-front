/**
 * Mirrors the front build's legacy-product redirect map into the backend Worker.
 *
 * Why the Worker owns these rules: Cloudflare Pages caps `_redirects` and drops
 * whatever overflows *without failing the build*. The retired-URL family is the
 * one part of that file that grows with the catalogue (every re-homed
 * `/products/other/<id>` listing needs its own line), so it now lives in the
 * Worker, whose route table has no budget. Pages keeps only the bare app roots
 * and the SPA prefix fallback.
 *
 * Source of truth stays in the front repo: the prerender computes the map from
 * live CMS data and publishes it as dist/data/legacy-redirects.json (exact
 * path -> path, plus 1:1 prefix pairs). This script mirrors that file into
 * backend/api/worker/src/legacyRedirects.generated.ts and keeps a marked block
 * of Worker routes in backend/api/worker/wrangler.toml in sync — without the
 * routes the Worker never sees the request, because Pages answers the SPA
 * shell first.
 *
 * Route patterns emitted (deliberately few — every pattern intercepts real
 * traffic, and the Worker answers 404 for anything it does not redirect):
 *   - one `<prefix>/*` per 1:1 prefix rule (also covers its trailing-slash
 *     form, because `*` matches the empty string);
 *   - one `/<prefix>/other/*` wildcard for the abolished other bucket, so its
 *     per-product 301s and their slash forms all reach the handler; unknown
 *     ids fall through to a scoped Pages passthrough in index.ts;
 *   - one exact pattern per remaining exact rule whose path is not already
 *     covered by one of the wildcards above.
 *
 * Run from front/ after any catalogue change:
 *   npm run build && node scripts/sync_redirects_to_worker.mjs
 * then redeploy the Worker (needs a Cloudflare API token; nothing is stored
 * locally). Re-running is idempotent: the wrangler.toml block is replaced
 * wholesale between its markers.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve } from "node:path";

const root = process.cwd();

const mapPath = resolve(root, "dist", "data", "legacy-redirects.json");
if (!existsSync(mapPath)) {
  console.error(`missing ${mapPath} — run \`npm run build\` first (the prerender computes the map from live CMS data)`);
  process.exit(1);
}

const map = JSON.parse(readFileSync(mapPath, "utf8"));
const exact = Object.entries(map.exact || {}).map(([from, to]) => [String(from), String(to)]);
const prefix = (map.prefix || []).map(([from, to]) => [String(from), String(to)]);
if (!exact.length && !prefix.length) {
  console.error(`${mapPath} carries no rules — refusing to wipe the Worker's redirect table`);
  process.exit(1);
}

const OTHER_BUCKET = "/products/other";
const otherBucketExact = exact.filter(([from]) => from.startsWith(`${OTHER_BUCKET}/`));
const needsOtherWildcard = otherBucketExact.length > 0;

// Which exact rules still need their own pattern. An exact rule is covered when
// a 1:1 prefix rule already intercepts everything beneath it (its trailing-
// slash form included), or when the other-bucket wildcard does.
const isCovered = (from) =>
  prefix.some(([prefixFrom]) => from.startsWith(`${prefixFrom}/`))
  || (needsOtherWildcard && from.startsWith(`${OTHER_BUCKET}/`));

// Both slash shapes, because Cloudflare matches a route pattern literally: a
// rule keyed without the trailing slash (the shape the Worker looks up) does
// NOT intercept a request for the slash form, and a retired directory-style
// URL is exactly the one that gets requested with the slash. Emitting both is
// still exact — neither pattern widens onto paths the rule does not own, which
// is why this is not done with a `/*` pattern.
const uncoveredExactPaths = exact.filter(([from]) => !isCovered(from)).map(([from]) => from);
const patterns = [
  ...prefix.map(([from]) => `balancebiketoddler.com${from}/*`),
  ...(needsOtherWildcard ? [`balancebiketoddler.com${OTHER_BUCKET}/*`] : []),
  ...uncoveredExactPaths.flatMap((from) => [`balancebiketoddler.com${from}`, `balancebiketoddler.com${from}/`]),
];

const header = `// AUTO-GENERATED by front/scripts/sync_redirects_to_worker.mjs — do not edit by hand.
// Source of truth: the front build's dist/data/legacy-redirects.json, computed
// by scripts/prerender-pages.ts from live CMS data. Cloudflare Pages caps
// _redirects, so this family lives here instead; re-sync after any catalogue
// change:  cd front && npm run build && node scripts/sync_redirects_to_worker.mjs
`;

const outFile = resolve(root, "..", "backend", "api", "worker", "src", "legacyRedirects.generated.ts");
writeFileSync(
  outFile,
  `${header}
/**
 * Exact retired path -> canonical path. Keyed on the no-trailing-slash form;
 * the handler strips the slash before lookup, and every slash form is covered
 * by a Worker route pattern (see wrangler.toml).
 */
export const LEGACY_PRODUCT_REDIRECTS: Record<string, string> = {
${exact.map(([from, to]) => `  ${JSON.stringify(from)}: ${JSON.stringify(to)},`).join("\n")}
};

/**
 * Retired prefix -> canonical prefix. Anything under \`from\` maps 1:1, which is
 * what the old \`/products/<legacy>/* -> /products/<kebab>/:splat\` _redirects
 * rules did. The abolished /products/other/ bucket is deliberately absent: its
 * per-product targets are exact rules above, and unknown ids must keep hitting
 * the SPA shell rather than a misleading redirect.
 */
export const LEGACY_CATEGORY_PREFIX_REDIRECTS: ReadonlyArray<readonly [string, string]> = [
${prefix.map(([from, to]) => `  [${JSON.stringify(from)}, ${JSON.stringify(to)}],`).join("\n")}
];
`,
  "utf8",
);
console.log(
  `wrote ${outFile} (${exact.length} exact + ${prefix.length} prefix rule(s), ${otherBucketExact.length} in the other bucket)`,
);

// --- keep the Worker routes in wrangler.toml in lockstep ---------------------
const MARKER = "# --- generated: legacy product URL routes (sync_redirects_to_worker.mjs) ---";
const END_MARKER = "# --- end legacy product URL routes ---";
const tomlPath = resolve(root, "..", "backend", "api", "worker", "wrangler.toml");
let toml = readFileSync(tomlPath, "utf8");
const routeBlock = [
  MARKER,
  "# Retired legacy product URLs (underscore category dirs + the abolished",
  "# /products/other/ bucket) 301 to their kebab-case successors — see",
  "# LEGACY_PRODUCT_REDIRECTS / LEGACY_CATEGORY_PREFIX_REDIRECTS in",
  "# src/legacyRedirects.generated.ts. Pages no longer carries these rules.",
  ...patterns.map(
    (pattern) => `[[routes]]
pattern = "${pattern}"
zone_name = "balancebiketoddler.com"`,
  ),
  END_MARKER,
  "",
].join("\n");

const markerIdx = toml.indexOf(MARKER);
if (markerIdx === -1) {
  const firstRoute = toml.indexOf("[[routes]]");
  if (firstRoute === -1) throw new Error("wrangler.toml has no [[routes]] section");
  toml = `${toml.slice(0, firstRoute)}${routeBlock}\n${toml.slice(firstRoute)}`;
} else {
  // Replace the whole block. The END marker is mandatory: the block itself
  // contains [[routes]] entries, so scanning for the next [[routes]] would stop
  // inside it and duplicate every pattern on each re-run — which is what makes
  // `wrangler deploy` fail with Cloudflare error 10020.
  const endMarkerIdx = toml.indexOf(END_MARKER, markerIdx + MARKER.length);
  if (endMarkerIdx === -1) {
    throw new Error(`wrangler.toml has the start marker but no "${END_MARKER}" — repair the block by hand once, then re-run`);
  }
  const afterEnd = endMarkerIdx + END_MARKER.length;
  const tail = toml.slice(afterEnd).replace(/^\n+/, "\n");
  toml = `${toml.slice(0, markerIdx)}${routeBlock}${tail}`;
}
writeFileSync(tomlPath, toml, "utf8");

// Guard: duplicate patterns are exactly what broke `wrangler deploy` on
// 2026-10-18 (error 10020). Fail loudly here instead of at deploy time.
const allPatterns = [...toml.matchAll(/^pattern = "([^"]+)"/gm)].map(([, pattern]) => pattern);
const duplicates = allPatterns.filter((pattern, i) => allPatterns.indexOf(pattern) !== i);
if (duplicates.length) {
  throw new Error(`Duplicate route patterns in wrangler.toml: ${[...new Set(duplicates)].join(", ")}`);
}
console.log(
  `updated legacy-product routes in ${tomlPath} (${patterns.length} generated, ${allPatterns.length} route(s) total)`,
);
